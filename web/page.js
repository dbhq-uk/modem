function startWiredWaterfall(endpoint) {
  stopWiredWaterfall();
  const draw = () => {
    try {
      wiredWaterfall.frame(endpoint.analyser, endpoint.ctx.sampleRate);
    } catch (err) {
      console.error('wired waterfall draw failed', err);
      return;
    }
    wiredWaterfallRaf = requestAnimationFrame(draw);
  };
  wiredWaterfallRaf = requestAnimationFrame(draw);
}

